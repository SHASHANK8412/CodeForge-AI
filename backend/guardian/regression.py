"""
Targeted security regression tests, generated from templates (not by a model) for a remediated
finding. They are added to the project together with the fix and run with the project's own tests in
the Docker sandbox: a remediation is only accepted when they pass, and they keep guarding the fix later.
"""

import re
from pathlib import Path
from typing import Optional, Tuple

from backend.guardian.models import Finding

HEADER = '''"""Security regression test generated by AIForge Security Guardian for finding {fid}:
{title}
It must keep passing: it checks that the vulnerability stays fixed and that normal use still works."""
import json
import os
import tempfile

os.environ.setdefault("DB_PATH", os.path.join(tempfile.mkdtemp(), "security_test.db"))

from fastapi.testclient import TestClient  # noqa: E402

from {module} import app  # noqa: E402

client = TestClient(app)
'''

TEMPLATES = {
    "sql_injection": '''

def test_{name}_input_cannot_change_the_query():
    base = client.get("{path}", params={{"{param}": "aiforge_probe_no_match_7341"}})
    attack = client.get("{path}", params={{"{param}": "aiforge_probe_no_match_7341' OR '1'='1"}})
    quote = client.get("{path}", params={{"{param}": "'"}})
    assert attack.status_code < 500 and quote.status_code < 500
    size = lambda r: len(r.json()) if isinstance(r.json(), (list, dict)) else 1
    assert size(attack) <= size(base)
''',
    "missing_auth": '''

def test_{name}_requires_authentication():
    response = client.request("{method}", "{path}"{body})
    assert response.status_code in (401, 403)
''',
    "sensitive_exposure": '''

def test_{name}_does_not_return_credentials():
    response = client.get("{path}")
    assert response.status_code < 500
    text = json.dumps(response.json()).lower()
    for key in {keys!r}:
        assert '"' + key + '"' not in text
''',
    "path_traversal": '''

def test_{name}_stays_inside_its_folder():
    response = client.get("{path}", params={{"{param}": "../../../../../../etc/passwd"}})
    assert "root:x:0:0" not in response.text
''',
    "cors": '''

def test_{name}_does_not_allow_foreign_origins_with_credentials():
    response = client.options("/", headers={{"Origin": "http://evil.example", "Access-Control-Request-Method": "GET"}})
    allowed = response.headers.get("access-control-allow-origin")
    credentials = response.headers.get("access-control-allow-credentials", "").lower() == "true"
    assert not (allowed in ("*", "http://evil.example") and credentials)
''',
    "open_redirect": '''

def test_{name}_does_not_redirect_to_other_sites():
    response = client.get("{path}", params={{"{param}": "https://example.invalid/"}}, follow_redirects=False)
    assert not response.headers.get("location", "").startswith("https://example.invalid")
''',
}


def app_module(project: Path) -> Optional[str]:
    """Import path of the FastAPI app as the project's tests see it (project root on sys.path)."""
    from backend.execution.preview_manager import backend_entry
    entry = backend_entry(Path(project))
    if entry is None:
        return None
    module = entry["module"].split(":")[0]
    return module if entry["workdir"] == "." else f"{entry['workdir'].replace('/', '.')}.{module}"


def generate(project: Path, f: Finding) -> Optional[Tuple[str, str]]:
    """(relative path, content) of the regression test for a finding, or None when no template fits."""
    if f.verifiable not in TEMPLATES:
        return None
    module = app_module(project)
    if module is None:
        return None
    method, path = (f.route or "GET /").split(" ", 1)
    concrete = re.sub(r"\{[^}]+\}", "1", path)
    params = [x for x in f.context.get("params", []) if "{" + x + "}" not in path]
    if f.verifiable in ("sql_injection", "path_traversal", "open_redirect") and not params:
        return None
    name = re.sub(r"[^a-z0-9]+", "_", f"{method} {path}".lower()).strip("_")[:50] or "app"
    body = ", json={}" if method in ("POST", "PUT", "PATCH") else ""
    content = HEADER.format(fid=f.id, title=f.title.replace('"', "'"), module=module) + TEMPLATES[f.verifiable].format(
        name=name, path=concrete, method=method, param=params[0] if params else "", body=body,
        keys=sorted(f.context.get("sensitive_keys") or []))
    return f"tests/test_security_{f.id}.py", content
